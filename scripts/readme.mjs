import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { countPurposes, linkState, loadCollection } from './collection.mjs';
import { marketUrl } from './entry.mjs';

export const PLACEMENTS = ['market-hero', 'market-grid', 'market-category'];
export const BLOCK_START = '<!-- collection:start -->';
export const BLOCK_END = '<!-- collection:end -->';

export function trackedUrl(id, placement) {
  if (!PLACEMENTS.includes(placement)) throw new Error(`Unknown placement ${placement}`);
  return `${marketUrl(id)}?utm_source=github&utm_medium=readme&utm_campaign=${placement}`;
}

const escapeMarkdown = (text) => text.replace(/[\\`*_[\]<>|]/g, '\\$&');

function renderItem(entry, deployments, placement) {
  const title = escapeMarkdown(entry.title);
  const label = linkState(entry, deployments) === 'none' ? title : `[${title}](${trackedUrl(entry.id, placement)})`;
  return `- ${label}: ${escapeMarkdown(entry.summary)}`;
}

export function renderBlock({ purposes, entries, deployments }) {
  const { total, counts } = countPurposes(purposes, entries);
  const sorted = [...entries].sort((a, b) => (a.id < b.id ? -1 : 1));
  const lines = [
    BLOCK_START,
    '<!-- Generated by scripts/readme.mjs. Edit entries or tags, then run it again. -->',
    '',
    '| Purpose | Items |',
    '| --- | ---: |',
    ...counts.map(({ label, count }) => `| ${label} | ${count} |`),
    `| **All items (each counted once)** | **${total}** |`,
    '',
  ];
  if (total === 0) lines.push('No items are listed yet.', '');
  else {
    lines.push('### All items', '', ...sorted.map((entry) => renderItem(entry, deployments, 'market-grid')), '');
    for (const { id, label, count } of counts.filter(({ count }) => count > 0)) {
      lines.push(`### ${label} (${count})`, '', ...sorted.filter((entry) => entry.purposes.includes(id)).map((entry) => renderItem(entry, deployments, 'market-category')), '');
    }
  }
  lines.push(BLOCK_END);
  return lines.join('\n');
}

export function replaceBlock(readme, block) {
  const start = readme.indexOf(BLOCK_START);
  const end = readme.indexOf(BLOCK_END);
  if (start === -1 || end < start) throw new Error('README.md has no collection block markers');
  return readme.slice(0, start) + block + readme.slice(end + BLOCK_END.length);
}

function main() {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..');
  const collection = loadCollection(root);
  if (collection.errors.length > 0) {
    console.error(collection.errors.join('\n'));
    process.exit(1);
  }
  const path = join(root, 'README.md');
  const current = readFileSync(path, 'utf8');
  const next = replaceBlock(current, renderBlock(collection));
  if (process.argv.includes('--check')) {
    if (next !== current) {
      console.error('README.md collection block is stale. Run: node scripts/readme.mjs');
      process.exit(1);
    }
  } else if (next !== current) writeFileSync(path, next);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
